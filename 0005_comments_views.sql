CREATE TABLE IF NOT EXISTS reel_comments(id INTEGER PRIMARY KEY AUTOINCREMENT,reel_id INTEGER NOT NULL,uid INTEGER NOT NULL,body TEXT NOT NULL,created INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS reel_comments_reel_idx ON reel_comments(reel_id,id);
CREATE TABLE IF NOT EXISTS story_views(story_id INTEGER NOT NULL,uid INTEGER NOT NULL,ts INTEGER NOT NULL,PRIMARY KEY(story_id,uid));
