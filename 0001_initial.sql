PRAGMA foreign_keys=ON;
CREATE TABLE IF NOT EXISTS users(
 id INTEGER PRIMARY KEY AUTOINCREMENT, username TEXT UNIQUE NOT NULL,
 salt TEXT NOT NULL, pw TEXT NOT NULL, avatar TEXT DEFAULT '', bio TEXT DEFAULT '',
 status TEXT DEFAULT 'CHOLLU-ൽ ഉണ്ട്', seen INTEGER DEFAULT 0,
 typ_to INTEGER DEFAULT 0, typ_at INTEGER DEFAULT 0, created INTEGER,
 email TEXT UNIQUE
);
CREATE TABLE IF NOT EXISTS sessions(token TEXT PRIMARY KEY,uid INTEGER NOT NULL,ts INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS sessions_uid_idx ON sessions(uid);
CREATE TABLE IF NOT EXISTS messages(
 id INTEGER PRIMARY KEY AUTOINCREMENT,from_id INTEGER NOT NULL,to_id INTEGER NOT NULL,
 kind TEXT NOT NULL,body TEXT NOT NULL,reply_to INTEGER DEFAULT 0,ts INTEGER NOT NULL,
 rd INTEGER DEFAULT 0,deleted INTEGER DEFAULT 0,exp INTEGER DEFAULT 0,edited INTEGER DEFAULT 0
);
CREATE INDEX IF NOT EXISTS ix1 ON messages(from_id,to_id,id);
CREATE INDEX IF NOT EXISTS ix2 ON messages(to_id,from_id,id);
CREATE TABLE IF NOT EXISTS reactions(msg_id INTEGER,uid INTEGER,emoji TEXT,PRIMARY KEY(msg_id,uid));
CREATE TABLE IF NOT EXISTS chat_cfg(a INTEGER,b INTEGER,ttl INTEGER DEFAULT 0,PRIMARY KEY(a,b));
CREATE TABLE IF NOT EXISTS blocks(a INTEGER,b INTEGER,PRIMARY KEY(a,b));
CREATE TABLE IF NOT EXISTS reports(id INTEGER PRIMARY KEY AUTOINCREMENT,by_id INTEGER,target INTEGER,reason TEXT,ts INTEGER);
CREATE TABLE IF NOT EXISTS fails(k TEXT PRIMARY KEY,n INTEGER,ts INTEGER);
CREATE TABLE IF NOT EXISTS grps(id INTEGER PRIMARY KEY AUTOINCREMENT,name TEXT,owner INTEGER,created INTEGER);
CREATE TABLE IF NOT EXISTS gmembers(gid INTEGER,uid INTEGER,lr INTEGER DEFAULT 0,PRIMARY KEY(gid,uid));
CREATE TABLE IF NOT EXISTS resets(uid INTEGER PRIMARY KEY,code TEXT,exp INTEGER,tries INTEGER DEFAULT 0);
CREATE TABLE IF NOT EXISTS push_subs(uid INTEGER,endpoint TEXT PRIMARY KEY,ts INTEGER);
CREATE TABLE IF NOT EXISTS sigs(id INTEGER PRIMARY KEY AUTOINCREMENT,from_id INTEGER,to_id INTEGER,kind TEXT,data TEXT,ts INTEGER);
CREATE INDEX IF NOT EXISTS sigs_to_id_idx ON sigs(to_id,id);
