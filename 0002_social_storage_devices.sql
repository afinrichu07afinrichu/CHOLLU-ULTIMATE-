PRAGMA foreign_keys=ON;
CREATE TABLE IF NOT EXISTS uploads(
 id TEXT PRIMARY KEY, owner INTEGER NOT NULL, chat_id INTEGER NOT NULL,
 object_key TEXT NOT NULL UNIQUE, upload_id TEXT, filename TEXT NOT NULL,
 content_type TEXT NOT NULL, size INTEGER NOT NULL, status TEXT NOT NULL DEFAULT 'pending',
 created INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS uploads_owner_idx ON uploads(owner,created);
CREATE TABLE IF NOT EXISTS stories(
 id INTEGER PRIMARY KEY AUTOINCREMENT, uid INTEGER NOT NULL, media_url TEXT NOT NULL,
 caption TEXT DEFAULT '', created INTEGER NOT NULL, expires INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS stories_exp_idx ON stories(expires,created);
CREATE TABLE IF NOT EXISTS reels(
 id INTEGER PRIMARY KEY AUTOINCREMENT, uid INTEGER NOT NULL, media_url TEXT NOT NULL,
 caption TEXT DEFAULT '', created INTEGER NOT NULL, likes INTEGER DEFAULT 0
);
CREATE TABLE IF NOT EXISTS reel_likes(reel_id INTEGER NOT NULL,uid INTEGER NOT NULL,PRIMARY KEY(reel_id,uid));
CREATE TABLE IF NOT EXISTS device_keys(uid INTEGER NOT NULL,device_id TEXT NOT NULL,label TEXT DEFAULT '',public_key TEXT NOT NULL,created INTEGER NOT NULL,last_seen INTEGER NOT NULL,PRIMARY KEY(uid,device_id));
CREATE TABLE IF NOT EXISTS e2ee_keys(uid INTEGER PRIMARY KEY,public_key TEXT NOT NULL,updated INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS admin_audit(id INTEGER PRIMARY KEY AUTOINCREMENT,admin_id INTEGER,action TEXT,details TEXT,created INTEGER);

CREATE TABLE IF NOT EXISTS download_tokens(token TEXT PRIMARY KEY,uid INTEGER NOT NULL,upload_id TEXT NOT NULL,exp INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS download_tokens_exp_idx ON download_tokens(exp);
